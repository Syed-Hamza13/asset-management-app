import { Router } from 'express';
import { requireAuth } from './middleware/auth.js';
import * as type from './modules/assetTypes/controller.js';
import * as field from './modules/fields/controller.js';
import * as dropdown from './modules/dropdowns/controller.js';
import * as asset from './modules/assets/controller.js';
import * as automation from './modules/assets/automationController.js';
import * as commonForm from './modules/commonForms/controller.js';
import * as commonAutomation from './modules/commonForms/automationController.js';

const router = Router();
router.use(requireAuth);
router.get('/common-form', commonForm.get);
router.put('/common-form', commonForm.save);
router.get('/common-form/automations', commonAutomation.list);
router.post('/common-form/automations', commonAutomation.create);
router.delete('/common-form/automations/:id', commonAutomation.remove);
router.get('/asset-types', type.list);
router.post('/asset-types', type.create);
router.get('/asset-types/:id', type.get);
router.patch('/asset-types/:id', type.update);
router.delete('/asset-types/:id', type.remove);
router.get('/asset-types/:assetTypeId/automations', automation.list);
router.post('/asset-types/:assetTypeId/automations', automation.create);
router.delete('/automations/:id', automation.remove);
router.get('/asset-types/:id/form', type.form);
router.put('/asset-types/:id/form', type.save);
router.get('/fields', field.list);
router.post('/fields', field.create);
router.get('/fields/:id', field.get);
router.patch('/fields/:id', field.update);
router.delete('/fields/:id', field.remove);
router.get('/dropdowns', dropdown.list);
router.post('/dropdowns', dropdown.create);
router.get('/dropdowns/:id', dropdown.get);
router.patch('/dropdowns/:id', dropdown.update);
router.delete('/dropdowns/:id', dropdown.remove);
router.post('/dropdowns/:id/options', dropdown.createOption);
router.patch('/dropdowns/:id/options/:optionId', dropdown.updateOptionController);
router.delete('/dropdowns/:id/options/:optionId', dropdown.removeOption);
router.get('/asset-types/:assetTypeId/assets/form', asset.form);
router.get('/asset-types/:assetTypeId/assets', asset.list);
router.post('/asset-types/:assetTypeId/assets', asset.create);
router.patch('/asset-types/:assetTypeId/assets/bulk', asset.bulkUpdate);
router.delete('/asset-types/:assetTypeId/assets/bulk', asset.bulkRemove);
router.get('/assets/:publicId', asset.get);
router.patch('/assets/:publicId', asset.update);
router.delete('/assets/:publicId', asset.remove);
export default router;
